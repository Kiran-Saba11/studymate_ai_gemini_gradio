# Import libraries
import gradio as gr
from google import genai

# ============================================================
# GEMINI API KEY
# ============================================================

# 🔐 Put your NEW Gemini API key between the quotes
GEMINI_API_KEY = ""

# Connect to Gemini
client = genai.Client(api_key=GEMINI_API_KEY)


# ============================================================
# STUDYMATE FUNCTION
# ============================================================

def studymate(task, text):

    if not text.strip():
        return "Please enter something first."

    if task == "Chat":
        prompt = f"""
You are StudyMate AI, an academic study assistant.

Answer the student's question clearly and simply.
Use examples when helpful.

Student question:
{text}
"""

    elif task == "Summarize":
        prompt = f"""
You are StudyMate AI.

Summarize the following text into simple study notes.
Include:
- Short summary
- Main points
- Important terms

Text:
{text}
"""

    elif task == "Generate Quiz":
        prompt = f"""
You are StudyMate AI.

Create a quiz about the following topic.

Create 5 multiple-choice questions.
Each question must have:
A, B, C, D options.

At the end, provide the correct answers.

Topic:
{text}
"""

    elif task == "Explain Topic":
        prompt = f"""
You are StudyMate AI.

Explain the following topic to a university student
in simple and understandable language.

Include:
1. Definition
2. Main concepts
3. Simple example
4. Real-world application
5. Short revision points

Topic:
{text}
"""

    try:

        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=prompt
        )

        return response.text

    except Exception as e:
        return f"Error: {e}"


# ============================================================
# GRADIO INTERFACE
# ============================================================

with gr.Blocks(title="StudyMate AI") as app:

    gr.Markdown(
        """
        # 📚 StudyMate AI

        **Your AI study assistant for learning, summarizing,
        quizzes, and topic explanations.**
        """
    )

    task = gr.Dropdown(
        choices=[
            "Chat",
            "Summarize",
            "Generate Quiz",
            "Explain Topic"
        ],
        value="Chat",
        label="Choose a Task"
    )

    text = gr.Textbox(
        label="Enter your question, text, or topic",
        placeholder="Example: Explain Artificial Intelligence",
        lines=8
    )

    button = gr.Button(
        "🚀 Ask StudyMate",
        variant="primary"
    )

    result = gr.Markdown(
        label="StudyMate Response"
    )

    button.click(
        fn=studymate,
        inputs=[task, text],
        outputs=result
    )


# ============================================================
# LAUNCH
# ============================================================

app.launch(share=True)